"""Ошибки updates. Ручки превращают их в HTTP-коды, сервисы про HTTP не знают."""


class UpdatesError(Exception):
    """Общий предок: ручке удобно ловить все ошибки модуля разом."""


class NotInstalled(UpdatesError):
    """Папки обмена с хостом нет: это разработка, а не установка на сервере."""


class Busy(UpdatesError):
    """Обновление уже ждёт в лотке или идёт."""


class NotAvailable(UpdatesError):
    """Просят не последнюю версию, обновляться нельзя или сайт не ответил."""
